object Lang {
    var cur = "ar"
    val list = listOf("ar" to "العربية", "en" to "English", "es" to "Español", "fr" to "Français", "de" to "Deutsch", "pt" to "Português", "ru" to "Русский", "zh" to "中文")
    fun isRtl(l: String = cur) = l == "ar"
    fun resolve(pref: String): String = if (pref != "auto" && list.any { it.first == pref }) pref else Locale.getDefault().language.let { l -> if (list.any { it.first == l }) l else "en" }
}

fun tr(id: String, vararg a: Any): String {
    val t = TABLE[Lang.cur]?.get(id) ?: TABLE["en"]?.get(id) ?: TABLE["ar"]?.get(id) ?: id
    return if (a.isEmpty()) t else String.format(Locale.ROOT, t, *a)
}

